-- 达梦 DM8 新旧写法对拍：比较"原 Oracle 写法"与"转换后 DM8 写法"在同一库上的求值结果
-- 每条语句必须返回三列：CASE_KEY / OLD_V / NEW_V，校验器会逐行比较 OLD_V 与 NEW_V
-- 适用前提：原写法本身也要能在 DM8 上执行。DB2 专有写法(SYSIBM、TIMESTAMPDIFF 两参数、
--           DIGITS 等)在 DM8 上无法执行，不在本文件覆盖范围，只能做 E2 语法验证。
-- 说明：带 "口径观测-" 前缀的用例预期就可能不同，用于把口径差异量化出来，不算缺陷。

-- [DIFF-01] T12 DECODE 对空串的匹配 vs 目标 CASE 写法
SELECT 'D1-空串DECODE-vs-CASE' AS CASE_KEY, DECODE('', NULL, 'match', 'nomatch') AS OLD_V, CASE WHEN '' IS NULL OR '' = '' THEN 'match' ELSE 'nomatch' END AS NEW_V FROM DUAL;

-- [DIFF-02] T4 DECODE 对 NULL 的匹配 vs 目标 CASE 写法
SELECT 'D2-NULL-DECODE-vs-CASE' AS CASE_KEY, DECODE(CAST(NULL AS VARCHAR(10)), NULL, 'match', 'nomatch') AS OLD_V, CASE WHEN CAST(NULL AS VARCHAR(10)) IS NULL THEN 'match' ELSE 'nomatch' END AS NEW_V FROM DUAL;

-- [DIFF-03] T9 VALUE/NVL 语义 vs COALESCE
SELECT 'D3-NVL-vs-COALESCE' AS CASE_KEY, NVL(CAST(NULL AS VARCHAR(10)), 'x') AS OLD_V, COALESCE(CAST(NULL AS VARCHAR(10)), 'x') AS NEW_V FROM DUAL;

-- [DIFF-04] T10 SUBSTR2 位置 0 的原始语义 vs SUBSTR(...,1,...) 目标写法
SELECT 'D4-SUBSTR0-vs-SUBSTR1' AS CASE_KEY, SUBSTR('abcdef', 0, 3) AS OLD_V, SUBSTR('abcdef', 1, 3) AS NEW_V FROM DUAL;

-- [DIFF-05] HR-003 空值/空串/纯空格删除判定：直接长度判定 vs COALESCE 包裹(CHANGE-388)
SELECT 'D5-空白删除判定' AS CASE_KEY, DECODE(LENGTH(TRIM('   ')), 0, 'hit', 'miss') AS OLD_V, DECODE(COALESCE(LENGTH(TRIM('   ')), 0), 0, 'hit', 'miss') AS NEW_V FROM DUAL;

-- [DIFF-06] T11/T13 加 1 天 vs 加 24/24 天
SELECT 'D6-加1天-vs-加24小时' AS CASE_KEY, TO_CHAR(CURRENT_TIMESTAMP + 1, 'YYYYMMDDHH24MISS') AS OLD_V, TO_CHAR(CURRENT_TIMESTAMP + 24.0/24, 'YYYYMMDDHH24MISS') AS NEW_V FROM DUAL;

-- [DIFF-07] T13 加 5 小时 vs 加 300/1440 天
SELECT 'D7-加5小时-vs-加300分' AS CASE_KEY, TO_CHAR(CURRENT_TIMESTAMP + 5.0/24, 'YYYYMMDDHH24MISS') AS OLD_V, TO_CHAR(CURRENT_TIMESTAMP + 300.0/1440, 'YYYYMMDDHH24MISS') AS NEW_V FROM DUAL;

-- [DIFF-08] 口径观测-日历日边界 vs 实际经过天数(HR-002 的核心分歧点，预期不同)
SELECT '口径观测-日历日vs实际天数' AS CASE_KEY, DATEDIFF(DAY, TO_TIMESTAMP('20260904235959','YYYYMMDDHH24MISS'), TO_TIMESTAMP('20260905000001','YYYYMMDDHH24MISS')) AS OLD_V, DATEDIFF(SECOND, TO_TIMESTAMP('20260904235959','YYYYMMDDHH24MISS'), TO_TIMESTAMP('20260905000001','YYYYMMDDHH24MISS')) / 86400 AS NEW_V FROM DUAL;

-- [DIFF-09] 口径观测-负时差整数除法的截断方向(预期为负，观察是向零还是向下)
SELECT '口径观测-负时差截断方向' AS CASE_KEY, DATEDIFF(SECOND, TO_TIMESTAMP('20260905100000','YYYYMMDDHH24MISS'), TO_TIMESTAMP('20260905093000','YYYYMMDDHH24MISS')) AS OLD_V, DATEDIFF(SECOND, TO_TIMESTAMP('20260905100000','YYYYMMDDHH24MISS'), TO_TIMESTAMP('20260905093000','YYYYMMDDHH24MISS')) / 3600 AS NEW_V FROM DUAL;
